CREATE TABLE IF NOT EXISTS HOC_SINH (
    MaHS BIGINT AUTO_INCREMENT PRIMARY KEY,
    MaSoHS VARCHAR(20) NOT NULL UNIQUE,
    HoTen VARCHAR(100) NOT NULL,
    NgaySinh DATE NOT NULL,
    GioiTinh VARCHAR(10) NOT NULL,
    DiaChi VARCHAR(255),
    SoDienThoai VARCHAR(20) UNIQUE,
    Email VARCHAR(100) UNIQUE,
    NgayTiepNhan DATE NOT NULL
);

-- 1. Bảng GIAO_VIEN (Giáo viên)
CREATE TABLE IF NOT EXISTS GIAO_VIEN (
    MaGV BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    MaSoGV VARCHAR(30),
    HoTen VARCHAR(150),
    NgaySinh DATE,
    SoDienThoai VARCHAR(20),
    Email VARCHAR(254),
    ChuyenMon VARCHAR(150),
    TrangThai VARCHAR(25) DEFAULT 'DANG_CONG_TAC'
);

-- 2. Bảng NGUOI_GIAM_HO (Người giám hộ)
CREATE TABLE IF NOT EXISTS NGUOI_GIAM_HO (
    MaNGH BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    HoTen VARCHAR(150),
    SoDienThoai VARCHAR(20),
    Email VARCHAR(254),
    DiaChi VARCHAR(500)
);

-- 3. Bảng HS_NGUOI_GIAM_HO (Học sinh - Người giám hộ)
CREATE TABLE IF NOT EXISTS HS_NGUOI_GIAM_HO (
    MaHS BIGINT UNSIGNED NOT NULL,
    MaNGH BIGINT UNSIGNED NOT NULL,
    MoiQuanHe VARCHAR(50),
    LienHeChinh TINYINT(1) DEFAULT 0,
    PRIMARY KEY (MaHS, MaNGH),
    CONSTRAINT fk_hsngh_hs FOREIGN KEY (MaHS) REFERENCES HOC_SINH(MaHS) ON DELETE CASCADE,
    CONSTRAINT fk_hsngh_ngh FOREIGN KEY (MaNGH) REFERENCES NGUOI_GIAM_HO(MaNGH) ON DELETE CASCADE
);

-- 4. Bảng VAI_TRO (Vai trò)
CREATE TABLE IF NOT EXISTS vai_tro (
    MaVT BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    MaSoVaiTro VARCHAR(40) NOT NULL UNIQUE,
    TenVaiTro VARCHAR(100) NOT NULL
);

-- 5. Bảng TAI_KHOAN (Tài khoản người dùng)
CREATE TABLE IF NOT EXISTS tai_khoan (
    MaTK BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    MaGV BIGINT UNSIGNED,
    TenDangNhap VARCHAR(100) NOT NULL UNIQUE,
    MatKhauBam VARCHAR(255) NOT NULL,
    HoTen VARCHAR(150),
    Email VARCHAR(254) UNIQUE,
    TrangThai VARCHAR(20) DEFAULT 'HOAT_DONG',
    TokenVersion INT UNSIGNED DEFAULT 0,
    CONSTRAINT fk_tai_khoan_giao_vien FOREIGN KEY (MaGV) REFERENCES GIAO_VIEN(MaGV) ON DELETE SET NULL
);

-- 6. Bảng TAI_KHOAN_VAI_TRO (Tài khoản - Vai trò)
CREATE TABLE IF NOT EXISTS tai_khoan_vai_tro (
    MaTK BIGINT UNSIGNED NOT NULL,
    MaVT BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (MaTK, MaVT),
    CONSTRAINT fk_tkvt_tk FOREIGN KEY (MaTK) REFERENCES tai_khoan(MaTK) ON DELETE CASCADE,
    CONSTRAINT fk_tkvt_vt FOREIGN KEY (MaVT) REFERENCES vai_tro(MaVT) ON DELETE CASCADE
);

-- 7. Bảng INVALIDATED_TOKENS (Token bị thu hồi)
CREATE TABLE IF NOT EXISTS invalidated_tokens (
    id VARCHAR(64) PRIMARY KEY,
    expire_time DATETIME(3) NOT NULL
);
